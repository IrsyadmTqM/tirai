const { chromium } = require('playwright');
(async () => {
  const D = process.argv[2];
  const b = await chromium.launch();
  const errs = [];
  const ctx = await b.newContext({ viewport: { width: 1360, height: 900 } });
  const p = await ctx.newPage();
  p.on('console', (m) => { if (['error', 'warning'].includes(m.type())) errs.push(m.text()); });
  p.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
  const terkirim = [];
  p.on('request', (r) => { if (r.url().includes('/api/data-saya/catatan') && r.method() === 'PUT') terkirim.push(r.postData()); });
  await p.goto('http://localhost:3000/masuk');
  await p.fill('#nama', 'donatur-01'); await p.fill('#sandi', 'tirai-demo');
  await p.click('button[type=submit]');
  await p.waitForSelector('#catatan-isi');
  const RAHASIA = 'Zakat mal 2026: tabungan 120 juta, emas 50 gram (sintetis).';
  await p.fill('#catatan-isi', RAHASIA);
  await p.fill('#catatan-sandi', 'sandi-catatan-panjang');
  await p.fill('#catatan-ulang', 'sandi-catatan-panjang');
  await p.click('button:has-text("Kunci dan simpan")');
  await p.waitForSelector('.bukti-kirim');
  await p.waitForTimeout(1400);
  console.log('badan PUT memuat teks asli?', terkirim.some((t) => t.includes('tabungan')), '| memuat kata sandi?', terkirim.some((t) => t.includes('sandi-catatan-panjang')));
  console.log('contoh badan PUT:', terkirim[0].slice(0, 120));
  await p.locator('#judul-catatan').scrollIntoViewIfNeeded();
  await p.screenshot({ path: D + '/l8-catatan-terkunci.png' });
  await p.reload();
  await p.waitForSelector('#catatan-buka');
  await p.fill('#catatan-buka', 'salah-tebak');
  await p.click('button:has-text("Buka catatan")');
  await p.waitForSelector('.pemberitahuan-galat');
  console.log('sandi salah ->', await p.textContent('.pemberitahuan'));
  await p.fill('#catatan-buka', 'sandi-catatan-panjang');
  await p.click('button:has-text("Buka catatan")');
  await p.waitForSelector('#catatan-isi');
  console.log('isi setelah dibuka sama?', (await p.inputValue('#catatan-isi')) === RAHASIA);
  console.log(errs.length ? 'GALAT:\n' + errs.join('\n') : 'tidak ada galat konsol');
  await b.close();
})();
