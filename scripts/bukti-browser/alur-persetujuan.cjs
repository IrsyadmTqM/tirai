const { chromium } = require('playwright');
(async () => {
  const D = process.argv[2];
  const b = await chromium.launch();
  const errs = [];
  const ctx = await b.newContext({ viewport: { width: 1360, height: 900 } });
  const p = await ctx.newPage();
  p.on('console', (m) => { if (['error', 'warning'].includes(m.type())) errs.push(m.text()); });
  p.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
  await p.goto('http://localhost:3000/masuk');
  await p.fill('#nama', 'donatur-01'); await p.fill('#sandi', 'tirai-demo');
  await p.click('button[type=submit]');
  await p.waitForSelector('.daftar-izin');
  const sakelar = p.locator('button[role=switch]').first();
  console.log('awal kontak_bukti aria-checked =', await sakelar.getAttribute('aria-checked'));
  await sakelar.click();
  await p.waitForSelector('.pemberitahuan');
  console.log('toast:', await p.textContent('.pemberitahuan'));
  console.log('setelah cabut aria-checked =', await sakelar.getAttribute('aria-checked'));
  const kontak = await p.locator('.tabel-data tr:has-text("Kontak") td').first().textContent();
  console.log('kontak di tabel sekarang:', kontak);
  await p.waitForTimeout(700);
  await p.locator('#judul-izin').scrollIntoViewIfNeeded();
  await p.screenshot({ path: D + '/l7-izin-dicabut.png' });
  await sakelar.click();
  await p.waitForSelector('#kontak-baru');
  await p.fill('#kontak-baru', 'ahmad.baru@contoh.test');
  await p.click('.form-kontak button');
  await p.waitForTimeout(900);
  const kontak2 = await p.locator('.tabel-data tr:has-text("Kontak") td').first().textContent();
  console.log('kontak setelah diisi ulang:', kontak2);
  console.log(errs.length ? 'GALAT:\n' + errs.join('\n') : 'tidak ada galat konsol');
  await b.close();
})();
